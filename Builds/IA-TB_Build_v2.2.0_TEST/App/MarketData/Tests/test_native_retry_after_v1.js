"use strict";
const assert=require("assert");
const Budget=require("../Orchestrator/request_budget");
const b=new Budget({mode:"NATIVE"});
b.configure("TEST",{shortLimit:1,shortWindowMs:60000,longLimit:10,longWindowMs:60000});
