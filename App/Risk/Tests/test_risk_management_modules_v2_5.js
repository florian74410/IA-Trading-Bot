'use strict';
const assert=require('node:assert/strict');
const risk=require('../Engine/risk_management_modules_v2_5');
const i={side:'BUY',entryPrice:70000,quantity:.1,stopLoss:68600,feePct:.1,slippagePct:.1};
const a={equity:10000},cfg={riskLevel:'BALANCED'};
const good=risk.r1(i,a,cfg);
assert.equal(good.decision,'RESIZE_OR_REJECT');assert.equal(good.modules.capital.notional,7000);
assert.equal(good.modules.stopLoss.lossEstimate,154);assert.equal(good.modules.budget.limitAmount,100);
assert.ok(good.modules.resize.proposedQuantity>0&&good.modules.resize.proposedQuantity<.1);
assert.equal(risk.r1({...i,stopLoss:71000},a,cfg).decision,'INSUFFICIENT_DATA');
assert.equal(risk.r1({...i,feePct:null},a,cfg).decision,'INSUFFICIENT_DATA');
assert.equal(risk.r1(i,a,{enabled:false}).decision,'DISABLED');
assert.equal(risk.r1(i,a,{r1:{budget:false,resize:false}}).decision,'PASS');
const snap={equity:9300,peakEquity:10000,positions:[{notional:6000,riskAtStop:200},{notional:1000,riskAtStop:190}],metrics:{correlation:{ok:true,alerts:[]},margin:{ok:true,alerts:[]},volatility:{ok:true,alerts:[]},freshness:{ok:true,alerts:[]}}};
const r=risk.r2(snap,cfg);assert.equal(r.decision,'LIMIT_EXCEEDED');assert.ok(r.warnings.includes('CONCENTRATION_LIMIT'));assert.ok(r.measurements.drawdownPct>0);
assert.equal(risk.r2({equity:10000,positions:[]},cfg).decision,'DEGRADED');
assert.equal(risk.r2(snap,{enabled:false}).decision,'DISABLED');
assert.equal(risk.r1(i,a,cfg).tokenCost,0);
console.log('PASS Risk Engine R1/R2 2.5 deterministic modules');
