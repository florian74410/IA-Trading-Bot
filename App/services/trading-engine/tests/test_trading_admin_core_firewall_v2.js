'use strict';
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const CP=require('../../../Core/Communication/communication_protocol_v1');
const {proofCodec}=require('../../../Core/Clients/auth21_ipc_proof');
const {issueTradingAdminProof}=require('../../../Core/Clients/auth21_trading_admin_issuer');
const {TradingFirewall,defaults}=require('../../../Core/Firewall/Protection/trading_firewall');
const secret=crypto.randomBytes(32),codec=proofCodec({secret});
const verifiedSessions={verifySession:token=>token==='admin'?{clientId:'CLadmin01',role:'ADMIN'}:{clientId:'CLuser01',role:'USER'}};
const payload={command:'EMERGENCY_STOP',command_id:'unique-admin-command-123',timestamp:Date.now(),confirmed:true};
const proof=issueTradingAdminProof({sessions:verifiedSessions,token:'admin',codec,payload});
assert.ok(proof);
assert.equal(issueTradingAdminProof({sessions:verifiedSessions,token:'user',codec,payload}),null);
const receiver=proofCodec({secret});
const grant=receiver.verify(proof,{audience:'trading',operation:'admin.write',method:'POST',ownerClientId:null,action:'trading.admin.command',bodyDigest:CP.hashData(payload)});
assert.equal(grant.role,'ADMIN');
assert.equal(receiver.verify(proof,{audience:'trading',operation:'admin.write',method:'POST',ownerClientId:null,action:'trading.admin.command',bodyDigest:CP.hashData(payload)}),null);
const firewall=new TradingFirewall({getConfig:()=>({...defaults(),enabled:false,mode:'OBSERVATION'}),audit:()=>{}});
const msg={action:'trading.admin.command',timestamp:Date.now(),request_id:'admin-001',arguments:{...payload,proof}};
assert.equal(firewall.inspect(msg,{cpAuthenticated:true,signatureValid:true,adminProofVerified:false}).ok,false);
assert.equal(firewall.inspect(msg,{cpAuthenticated:true,signatureValid:true,adminProofVerified:true}).ok,true);
console.log('PASS Core Auth21 issuer and Firewall guarded maintenance path');
