'use strict';
const assert=require('node:assert/strict');
const fc=require('../Fundamental/Providers/finance_calendar_provider_v2_4');
const entry={id:'us-cpi-october-2026',series_code:'us-cpi',name:'US CPI',country:'US',category:'economic-indicators',impact:'high',date:'2026-10-22',release_at_utc:'2026-10-22T12:30:00+00:00',consensus:'2.9%',prior:'3.0%',actual:null,unit:'%',status:'confirmed',source_name:'BLS',source_url:'https://www.bls.gov'};
const norm=fc.normalize(entry);
assert.equal(norm.calendar,'FINANCE_CALENDAR');
assert.equal(norm.impact,'HIGH');
assert.equal(norm.date,'2026-10-22');
assert.equal(norm.timeLabel,'12:30 UTC');
assert.equal(norm.consensus,'2.9%');
assert.equal(norm.prior,'3.0%');
assert.equal(norm.actual,null);
assert.equal(norm.sourceName,'BLS');
const data=fc.parse({events:[entry],total:1,attribution:{source:'financecalendar.com',terms:'with attribution'}});
assert.equal(data.events.length,1);
assert.equal(data.total,1);
assert.equal(data.attribution.url,'https://www.financecalendar.com');
assert.throws(()=>fc.parse({events:[]}),/SCHEMA/);
assert.equal(fc.normalize({date:'BAD',id:'1'}),null);
console.log('PASS Finance Calendar v2.4 normalization, schema and attribution');
