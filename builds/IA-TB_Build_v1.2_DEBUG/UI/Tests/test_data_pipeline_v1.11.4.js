'use strict';
var fs=require('fs'),path=require('path'),assert=require('assert');
var root=path.resolve(__dirname,'../..');
var app=fs.readFileSync(path.join(root,'Frontend/Pages/app_v1.0.html'),'utf8');
var md=fs.readFileSync(path.join(root,'MarketData/market_data_service.js'),'utf8');
var provider=fs.readFileSync(path.join(root,'MarketData/Provider/reference_provider.js'),'utf8');
assert(app.indexOf("/ui-data/market/candles?exchange='+encodeURIComponent(S.marketSource)")>=0,'UI must forward selected exchange to Market Data contract');
assert(md.indexOf("function normSource")>=0 && md.indexOf("source|symbol")<0,'Market Data must implement source-aware runtime');
assert(md.indexOf("key(s,t,source)")>=0,'Market Data cache key must include source');
assert(provider.indexOf("source==='GMX'")>=0,'Market Data provider must support GMX');
assert(provider.indexOf("KRAKEN_PUBLIC_REFERENCE")>=0,'Market Data provider must support Kraken');
var F=require(path.join(root,'Core/DataCollectorFirewall/data_collector_firewall'));
var fw=new F({duplicateWindowMs:5000});
var now=Date.now(),msg={provider:'KRAKEN_PUBLIC_REFERENCE',source:'KRAKEN_PUBLIC_REFERENCE',provenance:'KRAKEN_PUBLIC_REFERENCE',type:'OHLCV',symbol:'BTC/USD',timeframe:'1m',timestamp:now,data:[[now,100,101,99,100.5,1]]};
var a=fw.inspect(msg),b=fw.inspect(msg);
assert.notStrictEqual(a.decision,'REJECT','first valid snapshot must pass');
assert.notStrictEqual(b.decision,'REJECT','duplicate valid snapshot must not be rejected');
assert(b.warnings.some(function(x){return x.code==='DUPLICATE_DATA'}),'duplicate must remain observable as warning');
console.log('[DATA-PIPELINE] OK v1.11.4');
