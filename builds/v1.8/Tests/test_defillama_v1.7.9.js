'use strict';
var assert=require('assert');
var DefiLlama=require('../MarketData/Provider/defillama_provider');
var Catalog=require('../MarketData/Provider/capability_catalog');
var d=new DefiLlama();
var caps=d.capabilities();
assert.ok(caps.length>=25,'DefiLlama capability list incomplete');
assert.ok(caps.some(function(x){return x.command==='defillama.protocols.list'&&x.implemented===true;}));
assert.ok(caps.some(function(x){return x.command==='defillama.yields.pools'&&x.implemented===true;}));
assert.ok(caps.some(function(x){return x.command==='defillama.fees.summary'&&x.implemented===true;}));
assert.strictEqual(d.status().authentication,'PUBLIC_NO_KEY');
d.getCandles('BTCUSD','1h',function(e){assert.ok(e);assert.strictEqual(e.message,'DEFILLAMA_CANDLES_NOT_SUPPORTED');});
d.executeCommand('defillama.protocol.get',{},function(e){assert.ok(e);assert.strictEqual(e.message,'DEFILLAMA_PROTOCOL_REQUIRED');});
d.executeCommand('defillama.prices.current',{},function(e){assert.ok(e);assert.strictEqual(e.message,'DEFILLAMA_COINS_REQUIRED');});
var all=Catalog.all();
['REFERENCE','HYPERLIQUID','COINGECKO','BLOCKCHAIN','DEFILLAMA'].forEach(function(k){assert.ok(all[k],k+' missing from capability catalog');assert.ok(Array.isArray(all[k].commands)&&all[k].commands.length>0,k+' commands missing');});
assert.ok(all.BLOCKCHAIN.commands.some(function(x){return x.command==='market.orderbook.l3'&&x.status==='UPSTREAM_AVAILABLE';}));
assert.ok(all.HYPERLIQUID.commands.some(function(x){return x.command==='market.stream.trades'&&x.status==='IMPLEMENTED';}));
assert.ok(all.DEFILLAMA.commands.some(function(x){return x.command==='defillama.pro.unlocks'&&x.status==='UPSTREAM_AVAILABLE'&&x.auth==='PRO_API_KEY';}));
console.log('DefiLlama + Market capability catalogue tests: OK');
console.log('DefiLlama implemented commands:',caps.length);
